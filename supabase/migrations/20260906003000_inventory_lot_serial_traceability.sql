CREATE TABLE public.product_traceability_configs (
  product_id bigint PRIMARY KEY REFERENCES public.productos(id) ON DELETE CASCADE,
  mode text NOT NULL DEFAULT 'none' CHECK (mode IN ('none','lot','serial')),
  expiry_required boolean NOT NULL DEFAULT false,
  revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT traceability_expiry_mode CHECK (NOT expiry_required OR mode='lot')
);

CREATE TABLE public.inventory_lots (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES public.productos(id),
  warehouse_id bigint NOT NULL REFERENCES public.almacenes(id),
  lot_code text NOT NULL,
  expiry_date date NULL,
  base_quantity numeric(20,6) NOT NULL DEFAULT 0 CHECK (base_quantity >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT inventory_lot_code_valid CHECK (
    length(trim(lot_code)) BETWEEN 1 AND 100 AND lot_code !~ '[[:cntrl:]]'
  ),
  UNIQUE(product_id,warehouse_id,lot_code)
);

CREATE TABLE public.inventory_serials (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES public.productos(id),
  warehouse_id bigint NOT NULL REFERENCES public.almacenes(id),
  serial_number text NOT NULL,
  status text NOT NULL DEFAULT 'in_stock' CHECK (
    status IN ('in_stock','sold','transferred','written_off')
  ),
  received_request_id uuid NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT inventory_serial_number_valid CHECK (
    length(trim(serial_number)) BETWEEN 1 AND 160 AND serial_number !~ '[[:cntrl:]]'
  ),
  UNIQUE(product_id,serial_number)
);

CREATE TABLE public.inventory_traceability_receipts (
  request_id uuid PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES public.productos(id),
  warehouse_id bigint NOT NULL REFERENCES public.almacenes(id),
  mode text NOT NULL CHECK (mode IN ('lot','serial')),
  total_base_quantity numeric(20,6) NOT NULL CHECK (total_base_quantity > 0),
  inventory_request_id uuid NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX inventory_lots_product_warehouse_idx
  ON public.inventory_lots(product_id,warehouse_id,expiry_date);
CREATE INDEX inventory_serials_product_warehouse_idx
  ON public.inventory_serials(product_id,warehouse_id,status);

ALTER TABLE public.product_traceability_configs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inventory_lots ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inventory_serials ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inventory_traceability_receipts ENABLE ROW LEVEL SECURITY;
