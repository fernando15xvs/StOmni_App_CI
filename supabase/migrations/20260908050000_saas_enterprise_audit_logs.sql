-- Configuración principal: sólo nombres de campos cambiados; no se copian valores,
-- firmas, certificados, tokens ni otros secretos potenciales.
CREATE OR REPLACE FUNCTION private.audit_business_configuration_trigger()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path=''
AS $$
DECLARE
  v_allow text[] := ARRAY[
    'nombre_negocio','razon_social','ruc','direccion','telefono','email',
    'moneda','timezone','logo_url','serie_boleta','serie_factura','serie_nota_credito'
  ];
  v_changed jsonb;
BEGIN
  v_changed:=private.audit_changed_fields(to_jsonb(OLD),to_jsonb(NEW),v_allow);
  IF jsonb_array_length(v_changed)=0 THEN RETURN NEW; END IF;
  PERFORM private.write_audit_log(
    NEW.organization_id,'configuration.business.changed','business_configuration',NEW.id::text,
    TG_TABLE_NAME,TG_OP,NULL,jsonb_build_object('changed_fields',v_changed)
  );
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION private.audit_business_configuration_trigger() FROM PUBLIC,anon,authenticated;

