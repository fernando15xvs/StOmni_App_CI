-- Descuentos sensibles: registra sólo ventas con descuento y sólo campos de autorización.
CREATE OR REPLACE FUNCTION private.audit_sale_discount_trigger()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path=''
AS $$
DECLARE
  v_old_amount numeric := coalesce(OLD.descuento_global_monto,0);
  v_old_pct numeric := coalesce(OLD.descuento_global_porcentaje,0);
  v_new_amount numeric := coalesce(NEW.descuento_global_monto,0);
  v_new_pct numeric := coalesce(NEW.descuento_global_porcentaje,0);
BEGIN
  IF TG_OP='UPDATE'
     AND v_old_amount=v_new_amount
     AND v_old_pct=v_new_pct
     AND OLD.descuento_autorizado_por IS NOT DISTINCT FROM NEW.descuento_autorizado_por
     AND OLD.motivo_descuento IS NOT DISTINCT FROM NEW.motivo_descuento THEN
    RETURN NEW;
  END IF;
  IF v_new_amount<=0 AND v_new_pct<=0 THEN RETURN NEW; END IF;

  PERFORM private.write_audit_log(
    NEW.organization_id,'discount.applied','sale',NEW.id::text,TG_TABLE_NAME,TG_OP,NEW.request_id,
    jsonb_strip_nulls(jsonb_build_object(
      'discount_amount',NEW.descuento_global_monto,
      'discount_percentage',NEW.descuento_global_porcentaje,
      'authorized_by_employee_id',NEW.descuento_autorizado_por,
      'reason',left(coalesce(NEW.motivo_descuento,''),500),
      'gross_subtotal',NEW.subtotal_bruto,
      'sale_total',NEW.total
    ))
  );
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION private.audit_sale_discount_trigger() FROM PUBLIC,anon,authenticated;

