-- Mermas/ajustes/correcciones de inventario: no duplica ventas, compras o traslados ordinarios.
CREATE OR REPLACE FUNCTION private.audit_inventory_adjustment_trigger()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path=''
AS $$
DECLARE
  v_tipo text := lower(btrim(coalesce(NEW.tipo,'')));
  v_obs text := lower(btrim(coalesce(NEW.observaciones,'')));
  v_entity_id text := coalesce(NEW.id::text,NEW.producto_id::text);
BEGIN
  IF v_tipo NOT IN ('merma','ajuste','correccion','corrección')
     AND v_obs NOT LIKE '%ajuste%'
     AND v_obs NOT LIKE '%merma%'
     AND v_obs NOT LIKE '%correcci%' THEN
    RETURN NEW;
  END IF;

  PERFORM private.write_audit_log(
    NEW.organization_id,
    CASE WHEN v_tipo='merma' OR v_obs LIKE '%merma%' THEN 'stock.shrinkage' ELSE 'stock.adjusted' END,
    'inventory_movement',v_entity_id,TG_TABLE_NAME,TG_OP,NEW.request_id,
    jsonb_strip_nulls(jsonb_build_object(
      'product_id',NEW.producto_id,
      'warehouse_id',NEW.almacen_id,
      'movement_type',NEW.tipo,
      'balance',NEW.saldo,
      'incoming_quantity',NEW.ingreso_cant,
      'outgoing_quantity',NEW.salida_cant,
      'reason',left(coalesce(NEW.observaciones,''),500)
    ))
  );
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION private.audit_inventory_adjustment_trigger() FROM PUBLIC,anon,authenticated;

