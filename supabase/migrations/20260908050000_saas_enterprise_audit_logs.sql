-- Lectura paginada/filtrada. No se concede SELECT directo a Data API.
CREATE OR REPLACE FUNCTION public.list_audit_logs_v1(
  p_limit integer DEFAULT 100,
  p_before_id bigint DEFAULT NULL,
  p_action text DEFAULT NULL,
  p_entity_type text DEFAULT NULL
)
RETURNS SETOF jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path=''
AS $$
DECLARE
  v_org uuid := private.require_current_organization_id();
  v_limit integer := coalesce(p_limit,100);
BEGIN
  IF NOT private.has_permission('tenant.admin') THEN
    RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='Not authorized to read enterprise audit logs';
  END IF;
  IF v_limit<1 OR v_limit>200 THEN
    RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Audit page size must be between 1 and 200';
  END IF;

  RETURN QUERY
  SELECT jsonb_build_object(
    'id',a.id,
    'occurred_at',a.occurred_at,
    'actor_user_id',a.actor_user_id,
    'actor_employee_id',a.actor_employee_id,
    'actor_label',a.actor_label,
    'actor_role',a.actor_role,
    'action',a.action,
    'entity_type',a.entity_type,
    'entity_id',a.entity_id,
    'source_table',a.source_table,
    'source_operation',a.source_operation,
    'request_id',a.request_id,
    'metadata',a.metadata
  )
  FROM public.audit_logs a
  WHERE a.organization_id=v_org
    AND (p_before_id IS NULL OR a.id<p_before_id)
    AND (nullif(btrim(coalesce(p_action,'')),'') IS NULL OR a.action=p_action)
    AND (nullif(btrim(coalesce(p_entity_type,'')),'') IS NULL OR a.entity_type=p_entity_type)
  ORDER BY a.id DESC
  LIMIT v_limit;
END;
$$;

REVOKE ALL ON FUNCTION public.list_audit_logs_v1(integer,bigint,text,text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.list_audit_logs_v1(integer,bigint,text,text) TO authenticated;

COMMIT;
