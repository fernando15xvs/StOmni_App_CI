-- Fase 6.1 SaaS: auditoría empresarial transversal, append-only y tenant-aware.
BEGIN;

CREATE TABLE public.audit_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id uuid NOT NULL REFERENCES public.organizations(id) ON DELETE RESTRICT,
  occurred_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  actor_user_id uuid,
  actor_employee_id bigint,
  actor_label text,
  actor_role text,
  action text NOT NULL CHECK (action ~ '^[a-z][a-z0-9_.-]{2,80}$'),
  entity_type text NOT NULL CHECK (entity_type ~ '^[a-z][a-z0-9_.-]{1,80}$'),
  entity_id text,
  source_table text NOT NULL,
  source_operation text NOT NULL CHECK (source_operation IN ('INSERT','UPDATE','DELETE','RPC','SYSTEM')),
  request_id uuid,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(metadata)='object'),
  CHECK (pg_column_size(metadata) <= 32768)
);

COMMENT ON TABLE public.audit_logs IS 'Ledger empresarial append-only de acciones críticas. Metadata limitada y allowlisted; no almacena payloads completos ni secretos.';
COMMENT ON COLUMN public.audit_logs.actor_user_id IS 'auth.uid() observado al producir el evento; snapshot histórico, sin FK para preservar trazabilidad tras bajas.';
COMMENT ON COLUMN public.audit_logs.metadata IS 'Metadata segura y acotada. Nunca debe almacenar tokens, contraseñas, secretos, blobs ni filas completas.';

CREATE INDEX audit_logs_organization_time_idx
  ON public.audit_logs(organization_id, occurred_at DESC, id DESC);
CREATE INDEX audit_logs_organization_action_idx
  ON public.audit_logs(organization_id, action, id DESC);
CREATE INDEX audit_logs_organization_entity_idx
  ON public.audit_logs(organization_id, entity_type, entity_id, id DESC)
  WHERE entity_id IS NOT NULL;

ALTER TABLE public.audit_logs ENABLE ROW LEVEL SECURITY;

CREATE POLICY audit_logs_tenant_admin_select
ON public.audit_logs
FOR SELECT TO authenticated
USING (
  private.has_permission('tenant.admin')
  AND private.row_belongs_to_current_organization(organization_id)
);

REVOKE ALL ON TABLE public.audit_logs FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.audit_logs_id_seq FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION private.audit_pick_fields(
  p_row jsonb,
  p_fields text[]
)
RETURNS jsonb
LANGUAGE sql
IMMUTABLE
SECURITY INVOKER
SET search_path=''
AS $$
  SELECT coalesce(jsonb_object_agg(k, p_row->k), '{}'::jsonb)
  FROM unnest(coalesce(p_fields,'{}'::text[])) AS k
  WHERE p_row ? k
$$;

CREATE OR REPLACE FUNCTION private.audit_changed_fields(
  p_old jsonb,
  p_new jsonb,
  p_allowlist text[]
)
RETURNS jsonb
LANGUAGE sql
IMMUTABLE
SECURITY INVOKER
SET search_path=''
AS $$
  SELECT coalesce(jsonb_agg(k ORDER BY k), '[]'::jsonb)
  FROM unnest(coalesce(p_allowlist,'{}'::text[])) AS k
  WHERE (p_old->k) IS DISTINCT FROM (p_new->k)
$$;

CREATE OR REPLACE FUNCTION private.write_audit_log(
  p_organization_id uuid,
  p_action text,
  p_entity_type text,
  p_entity_id text,
  p_source_table text,
  p_source_operation text,
  p_request_id uuid DEFAULT NULL,
  p_metadata jsonb DEFAULT '{}'::jsonb
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path=''
AS $$
DECLARE
  v_session_org uuid := private.current_organization_id();
  v_user uuid := auth.uid();
  v_employee_id bigint;
  v_employee_label text;
  v_role text;
  v_id bigint;
  v_metadata jsonb := coalesce(p_metadata,'{}'::jsonb);
BEGIN
  IF p_organization_id IS NULL THEN
    RAISE EXCEPTION USING ERRCODE='23502', MESSAGE='Audit organization_id is required';
  END IF;
  IF v_user IS NOT NULL AND v_session_org IS DISTINCT FROM p_organization_id THEN
    RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='Cross-tenant audit event is not allowed';
  END IF;
  IF p_action IS NULL OR p_entity_type IS NULL OR p_source_table IS NULL OR p_source_operation IS NULL THEN
    RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Audit event fields are required';
  END IF;
  IF jsonb_typeof(v_metadata)<>'object' OR pg_column_size(v_metadata)>32768 THEN
    RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Audit metadata must be a JSON object <= 32 KiB';
  END IF;

  IF v_user IS NOT NULL THEN
    SELECT e.id, nullif(btrim(e.nombre),'')
      INTO v_employee_id, v_employee_label
    FROM public.empleados e
    WHERE e.organization_id=p_organization_id
      AND e.app_user_id=v_user
    ORDER BY e.id
    LIMIT 1;
    v_role:=private.current_base_role();
  ELSIF current_user='service_role' THEN
    v_role:='service_role';
    v_employee_label:='service_role';
  ELSE
    v_role:=current_user;
    v_employee_label:=current_user;
  END IF;

  INSERT INTO public.audit_logs(
    organization_id,actor_user_id,actor_employee_id,actor_label,actor_role,
    action,entity_type,entity_id,source_table,source_operation,request_id,metadata
  ) VALUES (
    p_organization_id,v_user,v_employee_id,v_employee_label,v_role,
    lower(p_action),lower(p_entity_type),nullif(p_entity_id,''),
    p_source_table,upper(p_source_operation),p_request_id,v_metadata
  )
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

